const BY_ID = Object.fromEntries(ACTIVITIES.map((a) => [a.id, a]));
export const activity = (id) => BY_ID[id] || BY_ID.other;

// kcal estimadas = MET × kg × horas
export const estimateKcal = (activityId, minutes, weightKg = 70) =>
  Math.round(activity(activityId).met * (weightKg || 70) * ((minutes || 0) / 60));
